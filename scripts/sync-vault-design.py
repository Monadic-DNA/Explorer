#!/usr/bin/env python3
"""Generate native resources from the checked-in Vault design sources (requires Inkscape)."""
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'design/vault'
ANDROID = ROOT / 'apps/android/app/src/main/res'
IOS = ROOT / 'apps/ios/Explorer'
ASSETS = IOS / 'Assets.xcassets'
ASSETS.mkdir(parents=True, exist_ok=True)
(ASSETS / 'Contents.json').write_text(json.dumps({'info': {'author': 'xcode', 'version': 1}}, indent=2)+'\n')
for source in sorted((SOURCE / 'art').glob('*.svg')):
    name = 'vault_' + source.stem.replace('-', '_')
    android = ANDROID / 'drawable-nodpi' / (name+'.png')
    android.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['inkscape', str(source), '--export-width=1000', '--export-filename='+str(android)], check=True, capture_output=True)
    asset = ASSETS / (name+'.imageset')
    asset.mkdir(exist_ok=True)
    shutil.copyfile(android, asset / (name+'.png'))
    (asset / 'Contents.json').write_text(json.dumps({'images': [{'filename': name+'.png', 'idiom':'universal'}], 'info':{'author':'xcode','version':1}}, indent=2)+'\n')
font_names = {'SpaceGrotesk-Light.ttf':'space_grotesk_light', 'SpaceGrotesk-Regular.ttf':'space_grotesk_regular', 'SpaceGrotesk-Bold.ttf':'space_grotesk_bold', 'EBGaramond-Medium.ttf':'eb_garamond_medium'}
for source, name in font_names.items():
    (ANDROID / 'font').mkdir(exist_ok=True)
    (IOS / 'Fonts').mkdir(exist_ok=True)
    shutil.copyfile(SOURCE / 'fonts' / source, ANDROID / 'font' / (name+'.ttf'))
    shutil.copyfile(SOURCE / 'fonts' / source, IOS / 'Fonts' / source)
for source in sorted((SOURCE / 'fonts').glob('*-OFL.txt')):
    (ANDROID / 'raw').mkdir(exist_ok=True)
    (IOS / 'Licenses').mkdir(exist_ok=True)
    shutil.copyfile(source, ANDROID / 'raw' / (source.stem.replace('-', '_') .lower()+'.txt'))
    shutil.copyfile(source, IOS / 'Licenses' / source.name)
colors = json.loads((SOURCE / 'colors.json').read_text())
kotlin = ['// Generated by scripts/sync-vault-design.py; edit design/vault/colors.json.', 'package com.monadicdna.explorer', '', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.graphics.colorspace.ColorSpaces', '', 'object VaultColors {']
for name, data in colors.items():
    asset = ASSETS / ('vault_'+name+'.colorset')
    asset.mkdir(exist_ok=True)
    (asset / 'Contents.json').write_text(json.dumps(data, indent=2)+'\n')
    color = data['colors'][0]['color']
    comp = color['components']
    rgb = [int(comp[c], 16) / 255 if comp[c].startswith('0x') else float(comp[c]) for c in ['red','green','blue']]
    alpha = comp.get('alpha', '1.000')
    alpha = int(alpha, 16) / 255 if alpha.startswith('0x') else float(alpha)
    space = 'DisplayP3' if color['color-space']=='display-p3' else 'Srgb'
    # Color(...) defaults to opaque; the sources carry real alpha (for example border at 0.5).
    kotlin.append(f'    val {name} = Color({rgb[0]:.8f}f, {rgb[1]:.8f}f, {rgb[2]:.8f}f, {alpha:.8f}f, ColorSpaces.{space})')
kotlin += ['}', '']
(ROOT / 'apps/android/app/src/main/java/com/monadicdna/explorer/VaultColors.kt').write_text('\n'.join(kotlin))

icon = ASSETS / 'AppIcon.appiconset'
icon.mkdir(exist_ok=True)
shutil.copyfile(SOURCE / 'app-icon.png', icon / 'AppIcon.png')
(icon / 'Contents.json').write_text(json.dumps({'images': [{'filename': 'AppIcon.png', 'idiom': 'universal', 'platform': 'ios', 'size': '1024x1024'}], 'info': {'author': 'xcode', 'version': 1}}, indent=2)+'\n')
shutil.copyfile(SOURCE / 'app-icon.png', ANDROID / 'drawable-nodpi' / 'vault_app_icon.png')
