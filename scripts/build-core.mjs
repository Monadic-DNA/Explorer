import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = spawnSync(process.env.CARGO || 'cargo', ['build', '--locked', '-p', 'explorer-core', '--release', '--target', 'wasm32-unknown-unknown'], { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const targetRoot = process.env.CARGO_TARGET_DIR || path.join(root, 'target');
const bytes = readFileSync(path.join(targetRoot, 'wasm32-unknown-unknown/release/explorer_core.wasm'));
const wasmModule = new WebAssembly.Module(bytes);
if (WebAssembly.Module.imports(wasmModule).length) throw new Error('Core WASM must have no platform imports');
mkdirSync(path.join(root, 'lib/generated'), { recursive: true });
writeFileSync(path.join(root, 'lib/generated/core-wasm.ts'), '// Generated by npm run core:build. Do not edit.\nexport const coreWasmBase64 = ' + JSON.stringify(bytes.toString('base64')) + ';\n');
console.log(`Built shared Rust core (${bytes.length} bytes, no platform imports).`);
